import assert from 'node:assert/strict';
import {seedState,toDoc} from '../lib/model';
import {parseProfileCsv,previewProfileImport,importProfileDrafts,CSV_MAX_BYTES} from '../lib/profile-import';
const state=seedState(),options={companyId:'demo-company',groupId:'demo-group',template:'visual' as const};
const csv='\uFEFFFull Name,Job Title,Email Address,Phone Number,Website\r\n"Doe, Jane","Sales ""Lead""",jane@example.com,+27210000000,https://example.com\r\n';
let preview=previewProfileImport(csv,state,options);
assert.equal(preview.ready,true);
assert.equal(preview.rows[0].details.name,'Doe, Jane');
assert.equal(preview.rows[0].details.role,'Sales "Lead"');
const before=structuredClone(state);
const result=importProfileDrafts(csv,state,options);
assert.deepEqual(state,before);
assert.equal(result.count,1);
assert.equal(result.state.profiles.length,state.profiles.length+1);
const profile=result.state.profiles.at(-1)!;
assert.equal(profile.companyId,options.companyId);assert.equal(profile.groupId,options.groupId);assert.equal(profile.template,'visual');
assert.equal(profile.live,null);assert.equal(profile.publicEnabled,false);assert.equal(profile.publishedAt,'');
assert.equal(profile.history.length,0);assert.equal(result.state.cards.length,state.cards.length);
assert.equal(toDoc(profile,result.state).accent,state.groups[0].color);
assert.equal(previewProfileImport(csv,result.state,options).ready,false);
assert.match(previewProfileImport(csv,result.state,options).rows[0].errors.join(' '),/existing profile/);
assert.equal(new Set(result.state.profiles.flatMap(p=>p.blocks.map(b=>b.id))).size,result.state.profiles.flatMap(p=>p.blocks).length);
assert.equal(previewProfileImport('name,email\nOne,same@example.com\nTwo,SAME@example.com',state,options).ready,false);
assert.equal(previewProfileImport('name\nSame\nsame',state,options).ready,false);
assert.equal(previewProfileImport('name,email\nMissing contact,not-an-email',state,options).ready,false);
assert.equal(previewProfileImport('name,website\nUnsafe,javascript:alert(1)',state,options).ready,false);
assert.equal(previewProfileImport('name,phone\nScientific phone,2.7E+10',state,options).ready,false);
assert.equal(previewProfileImport('name\n',state,options).ready,false);
assert.equal(previewProfileImport('role\nDeveloper',state,options).ready,false);
assert.equal(previewProfileImport('name,full_name\nOne,Two',state,options).ready,false);
assert.equal(previewProfileImport('name,private_note\nOne,Secret',state,options).ready,false);
assert.equal(previewProfileImport('name,email\nOne,one@example.com,extra',state,options).ready,false);
assert.equal(previewProfileImport('name,email\n,missing@example.com',state,options).ready,false);
assert.equal(previewProfileImport('name\n'+Array.from({length:97},(_,i)=>'Person '+i).join('\n'),state,options).ready,false);
assert.throws(()=>parseProfileCsv('name\n'+Array.from({length:101},(_,i)=>'Person '+i).join('\n')),/100/);
assert.throws(()=>parseProfileCsv('name\n"Unclosed'),/closing quote/);
assert.throws(()=>parseProfileCsv('name\n"Closed"junk'),/Unexpected text/);
assert.throws(()=>parseProfileCsv('name\nWrong"quote'),/Unexpected quote/);
assert.throws(()=>parseProfileCsv('é'.repeat(CSV_MAX_BYTES/2+1)),/256 KB/);
const multiline=parseProfileCsv('name,role\r\nJane,"First line\r\nSecond line"\r\nNext,Other\r\n');
assert.equal(multiline[1].cells[1],'First line\nSecond line');assert.equal(multiline[2].line,4);
assert.equal(previewProfileImport('name\nValid',state,{...options,companyId:'missing'}).ready,false);
assert.equal(previewProfileImport('name\nValid',state,{...options,groupId:'foreign'}).ready,false);
const other=structuredClone(state);other.companies.push({id:'other-company',name:'Other',industry:'',color:'#123456'});other.groups.push({id:'foreign',companyId:'other-company',name:'Other',color:'#123456',lockBrand:true});
assert.equal(previewProfileImport('name\nValid',other,{...options,groupId:'foreign'}).ready,false);
assert.equal(previewProfileImport('name,email\nNew Person,mia@example.com',other,{companyId:'other-company',groupId:'',template:'professional'}).ready,true);
assert.throws(()=>importProfileDrafts('name,email\nValid,new@example.com\nInvalid,broken',state,options));
assert.deepEqual(state,before);
const archived=structuredClone(result.state);archived.profiles.at(-1)!.archived=true;
assert.equal(previewProfileImport(csv,archived,options).ready,false);
console.log('Passed: CSV quoting/BOM/UTF-8 limits, row diagnostics, company/group ownership, duplicates, capacity, atomic draft creation and inherited branding.');

